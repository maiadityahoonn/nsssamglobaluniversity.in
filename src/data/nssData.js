const ACTIVITY_MONTH_MAP = {
  jan: 0, january: 0,
  feb: 1, february: 1,
  mar: 2, march: 2,
  apr: 3, april: 3,
  may: 4,
  jun: 5, june: 5,
  jul: 6, july: 6,
  aug: 7, august: 7,
  sep: 8, sept: 8, september: 8,
  oct: 9, october: 9,
  nov: 10, november: 10,
  dec: 11, december: 11,
};

export function parseActivityDate(dateStr = '') {
  const lower = dateStr.toLowerCase();
  const yearMatch = lower.match(/\b(20\d{2})\b/);
  const year = yearMatch ? parseInt(yearMatch[1], 10) : 2024;

  let month = 0;
  for (const [key, idx] of Object.entries(ACTIVITY_MONTH_MAP)) {
    if (new RegExp(`\\b${key}\\b`).test(lower)) {
      month = idx;
      break;
    }
  }

  const dayMatches = lower.match(/\b(\d{1,2})\b/g);
  let day = 1;
  if (dayMatches && dayMatches.length > 0) {
    const candidates = dayMatches.map(Number).filter((n) => n >= 1 && n <= 31);
    if (candidates.length > 0) {
      day = candidates[candidates.length - 1];
    }
  }

  return { year, month, timestamp: new Date(year, month, day).getTime() };
}

